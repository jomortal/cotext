"""The three-reading plan: the Reading plan's second factory plan (src/readingplan.ts), written as src/threeplan.ts.

A year of three readings a day, about a chapter in each - generated (2026-11-07) to the user's design:
  1. Psalms and the NT, the Psalms' five books between the NT's parts: Psalms 1-41, the Gospels, Psalms 42-72, Acts,
     Psalms 73-89, Paul's letters (Romans-Philemon), Psalms 90-106, Hebrews-Jude, Psalms 107-150, Revelation (410).
  2. Genesis-2 Chronicles: the Law and the history to the exile (403).
  3. Ezra-Malachi without the Psalms: the return, wisdom and the prophets (376).
Each list fits 365 days by reading two chapters on some days: the shortest neighbors (fewest verses together, from the
main database's words) joined, again and again, until 365 are left - so the days read two are short psalms, short
letters, the shortest chapters (Psalms 133-134, 2-3 John...). A day's join never crosses a category; it may cross books
(two readings then).

Output: src/threeplan.ts - THREEPLAN, 365 strings (Day 1 first; a day's readings joined by ";", each
"<book code> <chapter>[-<chapter>]", readingplan.ts' parse). Run: python3 pipeline/threeplan.py (after build_db.py).
"""
import pathlib
import sqlite3

from mcheyne import BOOKS, CHAPTERS

ROOT = pathlib.Path (__file__).resolve ().parent.parent
OUT = ROOT / "src" / "threeplan.ts"
DAYS = 365
IDX = {code: i for i, (_, code) in enumerate (BOOKS)}


def chapters (code, first = 1, last = None):
    b = IDX[code]
    return [(b, c) for c in range (first, (last or CHAPTERS[b]) + 1)]


def books (a, b):
    return [ch for i in range (IDX[a], IDX[b] + 1) for ch in chapters (BOOKS[i][1])]


CATEGORIES = [
    chapters ("Psa", 1, 41) + books ("Mat", "Jhn") + chapters ("Psa", 42, 72) + chapters ("Act")
    + chapters ("Psa", 73, 89) + books ("Rom", "Phm") + chapters ("Psa", 90, 106) + books ("Heb", "Jud")
    + chapters ("Psa", 107, 150) + chapters ("Rev"),
    books ("Gen", "2Ch"),
    books ("Ezr", "Job") + books ("Pro", "Mal"),
]


def fit (chs, verses):
    """The chapters in DAYS days: each day a run of chapters, the two neighbors with the fewest verses together joined
    until DAYS are left."""
    days = [[ch] for ch in chs]
    size = lambda d: sum (verses[ch] for ch in d)
    while len (days) > DAYS:
        i = min (range (len (days) - 1), key = lambda k: (size (days[k]) + size (days[k + 1]), k))
        days[i:i + 2] = [days[i] + days[i + 1]]
    return days


def readings (day):
    """A day's chapters as readings: a run within one book one reading ("Psa 133-134")."""
    out = []
    for b, c in day:
        if out and out[-1][0] == b and out[-1][2] == c - 1: out[-1][2] = c
        else: out.append ([b, c, c])
    return [f"{BOOKS[b][1]} {c1}" + (f"-{c2}" if c2 != c1 else "") for b, c1, c2 in out]


def main ():
    with sqlite3.connect (ROOT / "public" / "data" / "cotext.db") as con:
        verses = {(b - 1, c): n for b, c, n in con.execute ("SELECT book, chapter, MAX(verse) FROM words WHERE book <= 66 GROUP BY book, chapter")}
    cats = [fit (chs, verses) for chs in CATEGORIES]
    assert sum (len (c) for c in CATEGORIES) == 1189 and all (len (c) == DAYS for c in cats)
    rows = [";".join (r for cat in cats for r in readings (cat[i])) for i in range (DAYS)]
    OUT.write_text ("// The three-reading plan (generated, 2026-11-07): Psalms and the NT; Genesis-2 Chronicles; Ezra-Malachi without the\n"
                    "// Psalms - GENERATED by pipeline/threeplan.py: edit that, not this. A day a string, Day 1 first (365): its readings\n"
                    "// joined by \";\" (one a category, two where a day reads across books), each \"<book code> <chapter>[-<chapter>]\".\n"
                    "export const THREEPLAN = [\n" + "".join (f'  "{d}",\n' for d in rows) + "];\n", encoding = "utf-8")
    print (f"{OUT}: {DAYS} days; doubled: " + ", ".join (" + ".join (readings (d)) for cat in cats for d in cat if len (d) > 1))


if __name__ == "__main__":
    main ()
