def nile(south=24.0, w=0.45):
    """Egypt as the land the Nile waters: the delta and the valley (w degrees either side of the river) down to the
    latitude south."""
    river = [(31.25, 30.05), (31.1, 29.1), (30.8, 28.1), (31.2, 27.2), (31.7, 26.55), (32.7, 26.15), (32.6, 25.7),
             (32.9, 25.0), (32.9, 24.1), (32.6, 23.0), (31.6, 22.3), (31.3, 21.8), (30.6, 20.5), (30.4, 19.5),
             (31.8, 18.5)]
    valley = [p for p in river if p[1] >= south]
    return ([(29.4, 31.4), (30.3, 31.8), (31.6, 31.8), (32.6, 31.4), (32.4, 30.4)]
            + [(x + w, y) for x, y in valley] + [(x - w, y) for x, y in reversed(valley)]
            + [(30.4, 29.4), (29.9, 30.4)])


def kush(north=22.6, w=0.45):
    """The Nile's valley south of Egypt (Nubia, Kush) from the latitude north to Napata."""
    river = [(32.6, 23.0), (31.6, 22.3), (31.3, 21.8), (30.6, 20.5), (30.4, 19.5), (31.8, 18.5)]
    valley = [p for p in river if p[1] <= north + .5]
    return [(x + w, y) for x, y in valley] + [(x - w, y) for x, y in reversed(valley)]


